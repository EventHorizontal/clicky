#[test]
fn data_is_well_formed() {
    let mut is_data_well_formed = true;
    let mut entry_index = None; 
    let mut last_lower_bound = u64::MAX;
    for (index, (_, upper_bound, lower_bound)) in WORD_SET.into_iter().enumerate() {
        is_data_well_formed = last_lower_bound > upper_bound || upper_bound == last_lower_bound;
        if !is_data_well_formed {
            entry_index = Some(index); 
            break;
        }
        last_lower_bound = lower_bound;
    }
    assert!(is_data_well_formed, "Error in entry index {:?}", entry_index.unwrap());
}

#[test]
fn are_the_nt_words_equally_likely() {
    let nt_words = &WORD_SET[18..=26];
    let first_entry_chance = (nt_words[0].1 - nt_words[0].2) as f64 / DATASET_TOTAL_CF as f64;
    for (word, ub, lb) in nt_words.into_iter() {
        assert!(word.contains('\''), "all these words should contain an apostrophe");
        let chance = (ub - lb) as f64 / DATASET_TOTAL_CF as f64;
        println!("{}", chance);
        assert!(chance == first_entry_chance);
    }
}